def main():
    count=0
    for path in (ROOT/'godot/data').rglob('demo*.json'):
        data=json.loads(path.read_text());changed=False
        for npc in data.get('npcs',[]):
            id=npc['id']
            if id not in VOICES:continue
            greeting,route,repeat,ability,boss,testimony,ending,wish=VOICES[id]
            npc['dialogue']=[greeting,route]
            npc['story_dialogue']={'first_meet':[greeting,route],'repeat':[repeat], 'after_ability':[ability],
                'after_boss':[boss],'late_game':[testimony],'true_ending_branch':[ending]}
            npc['help']='F 继续交谈；也可以询问道路或心愿。'
            topics={'route':route,'wish':wish}
            if id in QUESTS:
                item,flag,reward,thanks=QUESTS[id]
                npc.setdefault('dialogue_meta',{})['quest_flag']=flag
                npc['story_dialogue']['sidequest_done']=[thanks]
                topics['quest']={'item':item,'complete_flag':flag,'accept_flag':'wish_accepted_'+id,'reward':reward,
                    'consume':item=='pollen_wax','thanks':thanks}
            npc['dialogue_topics']=topics;changed=True;count+=1
        if changed:
            data['map_title']=TITLES.get(data.get('art_theme',''),'巡礼地图')+' · 巡礼地图'
            data['chapter_name']=TITLES.get(data.get('art_theme',''),'绯线巡礼')
            data['interaction_design']={'key':'F','selection':'nearest_available','story_items':'manual_pickup','materials':'automatic_pickup','dialogue_choices':['continue','route','wish']}
            path.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    print('NPC dialogue records rewritten:',count,'distinct voices:',len(VOICES),'interactive wishes:',len(QUESTS))

if __name__=='__main__':main()
